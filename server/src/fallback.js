export function fallbackTopic(dayNumber, seen, fallbackTopics = FALLBACK_TOPICS) {
  const unseen = fallbackTopics.filter((t) => !(seen || []).includes(t.sk));
  const pool = unseen.length ? unseen : fallbackTopics;
  const t = pool[(dayNumber - 1) % pool.length];
  return {
    sk: t.sk,
    ru: t.ru,
    words: t.words.map((w) => ({ sk: w.sk, ru: w.ru })),
    example: t.example,
  };
}

export function localQuiz(topic) {
  if (!topic || !topic.words?.length) return [];
  const pool = shuffle(topic.words);
  const picked = pool.slice(0, Math.min(5, topic.words.length));
  return picked.map((w) => {
    const wrong = shuffle(topic.words.filter((x) => x.sk !== w.sk)).slice(0, 3).map((x) => x.ru);
    const options = shuffle([w.ru, ...wrong]);
    return { q: `Как переводится «${w.sk}»?`, options, answer: options.indexOf(w.ru) };
  });
}

function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}